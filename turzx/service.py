"""Install / remove the turzx daemon as a systemd user service."""
from __future__ import annotations

import os
import shutil
import subprocess
import sys

UNIT_NAME = "turzx.service"
UNIT_PATH = os.path.expanduser(f"~/.config/systemd/user/{UNIT_NAME}")
PKG_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _installed_as_package() -> bool:
    """True when 'turzx' is importable without this source tree on sys.path."""
    r = subprocess.run([sys.executable, "-I", "-c", "import turzx, os; print(os.path.abspath(turzx.__file__))"],
                       capture_output=True, text=True, cwd="/")
    return r.returncode == 0


def unit_text() -> str:
    env = "" if _installed_as_package() else f"Environment=PYTHONPATH={PKG_ROOT}\n"
    return f"""# generated by 'turzx service install'
[Unit]
Description=TURZX USB display (theme player)
Documentation=file://{PKG_ROOT}/README.md
After=default.target

[Service]
Type=simple
{env}Environment=PYTHONUNBUFFERED=1
ExecStart={sys.executable} -m turzx daemon
Restart=on-failure
RestartSec=5

[Install]
WantedBy=default.target
"""


def _systemctl(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(["systemctl", "--user", *args], text=True, capture_output=True, check=check)


def install(start: bool = True) -> int:
    if not shutil.which("systemctl"):
        print("Error: systemctl not found", file=sys.stderr)
        return 2
    os.makedirs(os.path.dirname(UNIT_PATH), exist_ok=True)
    if os.path.exists(UNIT_PATH) and "turzx service install" not in open(UNIT_PATH, encoding="utf-8").read():
        os.replace(UNIT_PATH, UNIT_PATH + ".bak")
        print(f"existing unit saved as {UNIT_PATH}.bak")
    with open(UNIT_PATH, "w", encoding="utf-8") as f:
        f.write(unit_text())
    _systemctl("daemon-reload")
    _systemctl("enable", UNIT_NAME)
    if start:
        _systemctl("restart", UNIT_NAME)
    print(f"installed {UNIT_PATH} (starts with your login)")
    return 0


def uninstall() -> int:
    _systemctl("disable", "--now", UNIT_NAME, check=False)
    if os.path.exists(UNIT_PATH):
        os.remove(UNIT_PATH)
    _systemctl("daemon-reload", check=False)
    print("service removed")
    return 0


def status() -> int:
    r = _systemctl("is-enabled", UNIT_NAME, check=False)
    a = _systemctl("is-active", UNIT_NAME, check=False)
    print(f"Service:    {UNIT_NAME} {r.stdout.strip() or 'not installed'}, {a.stdout.strip()}")
    print(f"Logs:       journalctl --user -u {UNIT_NAME} -f")
    return 0
